import { readFile, writeFile } from 'node:fs/promises';
const records = {};
const sources = [];
for (const [language, code] of [['es', 'spa'], ['en', 'eng']]) {
  records[language] = {};
  for (const book of ['hymns', 'hymns-for-home-and-church']) {
    const data = JSON.parse(await readFile(`output/hymn-topics/${code}-${book}-topics.json`, 'utf8'));
    sources.push({language, book, url: data.source, count: data.records.length});
    for (const record of data.records) {
      if (records[language][record.number]) throw new Error('Duplicate hymn number');
      records[language][record.number] = record;
    }
  }
}
const source = { retrieved: '2026-11-16', sources, hymns: records };
await writeFile('docs/hymn-topics-data.mjs', '// Generated by tools/build-hymn-topics.mjs. Official metadata only; no lyrics.\nexport const HYMN_TOPICS_DATA = ' + JSON.stringify(source, null, 2) + ';\n');
const quote = value => JSON.stringify(value).replaceAll('$', '\\$');
let kotlin = 'package com.example.agendasacramental\n\n// Generated by tools/build-hymn-topics.mjs; same source as web.\nobject OfficialHymnTopics {\n';
for (const language of ['es', 'en']) {
  const rows = Object.entries(records[language]);
  const chunks = [];
  for (let i = 0; i < rows.length; i += 60) {
    const name = `${language}${i / 60}`;
    chunks.push(`${name}()`);
    kotlin += `    private fun ${name}(): Map<Int, List<String>> = mapOf(\n` + rows.slice(i, i + 60).map(([number, record]) => `        ${number} to listOf(${record.topics.map(quote).join(', ')})`).join(',\n') + '\n    )\n';
  }
  kotlin += `    val ${language}: Map<Int, List<String>> by lazy { ${chunks.join(' + ')} }\n`;
}
kotlin += '}\n';
await writeFile('app/src/main/java/com/example/agendasacramental/OfficialHymnTopics.kt', kotlin);
console.log('Generated identical official topic catalogs for Android and web.');
